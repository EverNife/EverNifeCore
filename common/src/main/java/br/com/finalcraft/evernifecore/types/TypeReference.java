package br.com.finalcraft.evernifecore.types;

import br.com.finalcraft.evernifecore.EverNifeCore;
import br.com.finalcraft.evernifecore.action.EventSource;
import jakarta.annotation.Nullable;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.TreeMap;
import java.util.stream.Collectors;

/**
 * The reference generated from the live registries - one markdown file per kind, one table per type in registration
 * order - which {@code /ecore types export} writes. What a type says about itself is the documentation, so the page
 * cannot drift from the code.
 */
public final class TypeReference {

    private TypeReference() {
    }

    /** The kinds of every live registry ({@code condition}, {@code effect}, ...), sorted, each with its registries. */
    public static Map<String, List<TypeRegistry<?>>> getKinds() {
        Map<String, List<TypeRegistry<?>>> kinds = new TreeMap<>();
        for (TypeRegistry<?> registry : TypeRegistries.getAll()) {
            kinds.computeIfAbsent(registry.getKindName(), kind -> new ArrayList<>()).add(registry);
        }
        return kinds;
    }

    /**
     * Writes {@code types-<kind>.md} into {@code folder} for {@code kind}, or for every kind when it is null; the files
     * written, by kind. An unknown kind writes nothing.
     */
    public static List<File> write(File folder, @Nullable String kind) throws IOException {
        List<File> written = new ArrayList<>();
        Files.createDirectories(folder.toPath());
        for (Map.Entry<String, List<TypeRegistry<?>>> entry : getKinds().entrySet()) {
            if (kind != null && !entry.getKey().equalsIgnoreCase(kind)) {
                continue;
            }
            File file = new File(folder, "types-" + entry.getKey() + ".md");
            Files.write(file.toPath(), render(entry.getKey(), entry.getValue()).getBytes(StandardCharsets.UTF_8));
            written.add(file);
        }
        return written;
    }

    /** The markdown page of {@code kind}: a header, then one section per registered type. */
    public static String render(String kind, Collection<TypeRegistry<?>> registries) {
        StringBuilder page = new StringBuilder();
        page.append("# Types: ").append(kind).append("\n\n");
        page.append("Generated by `/ecore types export` on the platform `").append(EverNifeCore.getPlatform().getPlatformProviderId())
                .append("`: every ").append(kind).append(" type registered right now, in registration order.\n");
        for (TypeRegistry<?> registry : registries) {
            for (TypeDescriptor<?> descriptor : registry.getAll()) {
                renderType(page, registry, descriptor);
            }
        }
        return page.toString();
    }

    private static void renderType(StringBuilder page, TypeRegistry<?> registry, TypeDescriptor<?> descriptor) {
        page.append("\n## `").append(descriptor.getKey()).append("`\n\n");
        page.append(cell(descriptor.getDescription())).append("\n\n");
        page.append("| | |\n|---|---|\n");
        page.append("| Registered by | ").append(cell(registry.getOwner(descriptor).map(owner -> owner.getMetaInfo().getName()).orElse("-"))).append(" |\n");
        page.append("| Aliases | ").append(listOrDash(descriptor.getAliases())).append(" |\n");
        page.append("| Platforms | ").append(descriptor.getPlatforms().isEmpty() ? "every platform" : cell(String.join(", ", descriptor.getPlatforms()))).append(" |\n");
        page.append("| Sources | ").append(listOrDash(descriptor.getNeeds().stream().map(EventSource::toString).collect(Collectors.toList()))).append(" |\n");
        page.append("| Capabilities | ").append(listOrDash(descriptor.getNeededCapabilities().stream().map(Enum::name).collect(Collectors.toList()))).append(" |\n");
        Optional<String> unsupported = registry.getUnsupported(descriptor);
        page.append("| On this platform | ").append(unsupported.map(TypeReference::cell).orElse("supported")).append(" |\n");
        if (descriptor.getParams().isEmpty()) {
            page.append("\nNo parameters.\n");
            return;
        }
        page.append("\n| Parameter | Kind | Required | Default | Description |\n|---|---|---|---|---|\n");
        for (ParamSpec param : descriptor.getParams()) {
            String kind = param.getKind().name() + (param.getAccepted().isEmpty() ? "" : " (one of " + String.join(", ", param.getAccepted()) + ")");
            page.append("| `").append(param.getName()).append("` | ").append(cell(kind))
                    .append(" | ").append(param.isRequired() ? "yes" : "no")
                    .append(" | ").append(param.getDefault() == null ? "-" : cell(String.valueOf(param.getDefault())))
                    .append(" | ").append(cell(param.getDescription())).append(" |\n");
        }
    }

    private static String listOrDash(List<String> values) {
        return values.isEmpty() ? "-" : cell(String.join(", ", values));
    }

    //a pipe would end the cell, a newline the row
    private static String cell(String text) {
        return text == null || text.isEmpty() ? "-" : text.replace("|", "\\|").replace("\r", "").replace('\n', ' ');
    }
}
